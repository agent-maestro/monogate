#!/usr/bin/env python3
"""Compute the README status table from PROTOCOL.md. Enumerate-then-count: no hand-written status.

The arm statuses in README.md are generated by this script from the `**Status:` lines in PROTOCOL.md,
so the README cannot drift from the protocol. If they could disagree, the README would be a second
place for the truth to live.
"""
from __future__ import annotations
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROTOCOL = os.path.join(HERE, "PROTOCOL.md")


def arms() -> list[tuple[str, str, str]]:
    txt = open(PROTOCOL).read()
    out = []
    for m in re.finditer(r"^# (E\d) — (.+?)$", txt, re.M):
        tail = txt[m.end():]
        s = re.search(r"^\*\*Status:?\s*(.+?)\*\*", tail, re.M)
        status = s.group(1).strip().rstrip(".") if s else "UNKNOWN"
        out.append((m.group(1), m.group(2).strip(), status))
    return out


def main() -> int:
    a = arms()
    if not a:
        print("[UNAVAILABLE] no arms parsed from PROTOCOL.md — instrument failure, not zero arms.")
        return 2
    w = max(len(x[1]) for x in a)
    print(f"| arm | what it tests | status |")
    print(f"|---|---|---|")
    for aid, name, status in a:
        print(f"| **{aid}** | {name} | {status} |")
    print()
    print(f"_{len(a)} arms, computed from PROTOCOL.md by `status.py`._")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
