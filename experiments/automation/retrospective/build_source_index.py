#!/usr/bin/env python3
"""Enumerate the candidate sources for the E1 retrospective backfill. ENUMERATES ONLY — never classifies.

House rule 3 is enumerate-then-count, so the index is generated rather than hand-listed: a hand-written
list of "the logs we should audit" is exactly the kind of count that drifts from the tree it describes.

This script does NOT read the contents for classification purposes and MUST NOT be extended to. See
TEMPLATE.md for why an AI classifying these is a conflicted instrument.

Usage: build_source_index.py [--write]
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOTS = [
    ("monogate", "/home/monogate/monogate/monogate"),
    ("machlib", "/home/monogate/monogate/machlib"),
    ("monogate-research", "/home/monogate/monogate/monogate-research"),
    ("forge", "/home/monogate/monogate/forge"),
]
PATTERNS = ("FINDINGS.md", "MIGRATION_LOG.md", "_LOG.md", "SESSION", "STATE_OF_THE_WORK.md")


def find_docs(root: str) -> list[str]:
    out: list[str] = []
    if not os.path.isdir(root):
        return out
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames
                       if d not in (".git", "node_modules", ".lake", "dist", "__pycache__", ".venv")]
        for f in filenames:
            if any(p in f for p in PATTERNS):
                out.append(os.path.relpath(os.path.join(dirpath, f), root))
    return sorted(out)


def git_summary(root: str) -> tuple[int, str, str]:
    if not os.path.isdir(os.path.join(root, ".git")):
        return 0, "", ""
    n = subprocess.run(["git", "rev-list", "--count", "HEAD"], cwd=root,
                       capture_output=True, text=True).stdout.strip() or "0"
    first = subprocess.run(["git", "log", "--reverse", "--format=%as", "--max-count=1"], cwd=root,
                           capture_output=True, text=True).stdout.strip()
    last = subprocess.run(["git", "log", "-1", "--format=%as"], cwd=root,
                          capture_output=True, text=True).stdout.strip()
    return int(n), first, last


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="write SOURCE_INDEX.md")
    a = ap.parse_args()

    lines = ["# Retrospective source index — CANDIDATES ONLY, NOT AN AUDIT",
             "",
             "Generated by `build_source_index.py`. Regenerate rather than edit; a hand-maintained",
             "list of sources drifts from the tree it claims to describe.",
             "",
             "**Nothing here has been classified.** See `TEMPLATE.md` for why that is deliberate.",
             ""]
    total_docs = 0
    for name, root in ROOTS:
        n, first, last = git_summary(root)
        docs = find_docs(root)
        total_docs += len(docs)
        lines.append(f"## {name}")
        lines.append("")
        if not os.path.isdir(root):
            lines.append(f"`{root}` — **NOT FOUND at index time.** Recorded as unavailable, not as zero.")
            lines.append("")
            continue
        lines.append(f"- commits: **{n}** ({first} → {last})" if n else "- commits: (not a git repo)")
        lines.append(f"- candidate documents: **{len(docs)}**")
        lines.append("")
        if docs:
            lines.append("<details><summary>document list</summary>")
            lines.append("")
            for d in docs:
                lines.append(f"- `{d}`")
            lines.append("")
            lines.append("</details>")
            lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(f"**Totals, computed: {total_docs} candidate documents across "
                 f"{sum(1 for _, r in ROOTS if os.path.isdir(r))} located repo(s).**")
    lines.append("")
    lines.append("A repository listed as NOT FOUND is unavailable, not empty. Do not treat its absence")
    lines.append("as an absence of interventions to audit.")

    out = "\n".join(lines) + "\n"
    if a.write:
        p = os.path.join(HERE, "SOURCE_INDEX.md")
        open(p, "w").write(out)
        print(f"wrote {p}  ({total_docs} candidate documents enumerated)")
    else:
        print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
